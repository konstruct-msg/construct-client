//! Device linking screen — two modes:
//!
//! **SHOW** tab (default): this device asks to join an account. Its code (`konstruct://link-to-me`)
//!   is shown as a QR for the phone to scan and approve; the client waits for the approval
//!   (Flow B — a desktop has no camera, so this is the way in).
//!
//! **SCAN** tab: enter a link token from another device (`ConfirmDeviceLink`, Flow A).

use crate::theme::ThemeMode;
use ratatui::{
    buffer::Buffer,
    layout::Rect,
    text::{Line, Span},
    widgets::{Paragraph, Widget},
};

use super::qr_widget::QrWidget;

#[derive(Debug, Clone, PartialEq)]
pub enum DeviceLinkTab {
    /// Enter a token generated by another device.
    Scan,
    /// Show a QR / token for this device so another device can scan it.
    Show,
}

pub struct DeviceLinkScreen {
    pub theme: ThemeMode,
    pub tab: DeviceLinkTab,
    /// Token typed by the user (SCAN tab).
    pub token: String,
    /// Token generated by this device to display (SHOW tab). Set by the app
    /// after calling the GenerateDeviceLink RPC.
    pub own_token: Option<String>,
    pub status: Option<String>,
    pub is_error: bool,
}

impl DeviceLinkScreen {
    pub fn new() -> Self {
        Self {
            theme: ThemeMode::default(),
            tab: DeviceLinkTab::Show,
            token: String::new(),
            own_token: None,
            status: None,
            is_error: false,
        }
    }

    pub fn push_char(&mut self, c: char) {
        if self.tab == DeviceLinkTab::Scan && self.token.len() < 64 {
            self.token.push(c);
        }
    }

    pub fn pop_char(&mut self) {
        if self.tab == DeviceLinkTab::Scan {
            self.token.pop();
        }
    }

    /// Switch between SCAN and SHOW tabs (called on Tab key).
    pub fn toggle_tab(&mut self) {
        self.tab = match self.tab {
            DeviceLinkTab::Scan => DeviceLinkTab::Show,
            DeviceLinkTab::Show => DeviceLinkTab::Scan,
        };
    }

    pub fn set_status(&mut self, msg: impl Into<String>, error: bool) {
        self.status = Some(msg.into());
        self.is_error = error;
    }

    pub fn clear_status(&mut self) {
        self.status = None;
        self.is_error = false;
    }
}

impl Widget for &DeviceLinkScreen {
    fn render(self, area: Rect, buf: &mut Buffer) {
        let palette = self.theme.palette();
        // ── Tab bar ───────────────────────────────────────────────────────────
        let tab_show = if self.tab == DeviceLinkTab::Show {
            Span::styled(" [SHOW CODE] ", palette.selected())
        } else {
            Span::styled(" [SHOW CODE] ", palette.muted())
        };
        let tab_scan = if self.tab == DeviceLinkTab::Scan {
            Span::styled(" [ENTER TOKEN] ", palette.selected())
        } else {
            Span::styled(" [ENTER TOKEN] ", palette.muted())
        };
        let tab_hint = Span::styled("  Tab=switch   Esc=back", palette.muted());

        let tab_line = Line::from(vec![tab_show, tab_scan, tab_hint]);
        let tab_w = area.width;
        Paragraph::new(tab_line).style(palette.canvas()).render(
            Rect {
                x: area.x,
                y: area.y,
                width: tab_w,
                height: 1,
            },
            buf,
        );

        let content_area = Rect {
            x: area.x,
            y: area.y + 2,
            width: area.width,
            height: area.height.saturating_sub(2),
        };

        match self.tab {
            DeviceLinkTab::Scan => self.render_scan(content_area, buf),
            DeviceLinkTab::Show => self.render_show(content_area, buf),
        }
    }
}

impl DeviceLinkScreen {
    fn render_scan(&self, area: Rect, buf: &mut Buffer) {
        let palette = self.theme.palette();
        const TITLE: &str = " Link this device — enter token ";
        const HINT: &str = "Enter=confirm   Esc=back   q=quit";

        let total_h = 1u16 + 2 + 3 + 1 + 1 + 1 + 1;
        let v_offset = area.height.saturating_sub(total_h) / 2;
        let mut y = area.y + v_offset;

        let tw = TITLE.len() as u16;
        let tx = area.x + area.width.saturating_sub(tw) / 2;
        Paragraph::new(TITLE).style(palette.emphasis()).render(
            Rect {
                x: tx,
                y,
                width: tw.min(area.width),
                height: 1,
            },
            buf,
        );
        y += 2;

        let field_w = 50u16.min(area.width.saturating_sub(4));
        let field_x = area.x + area.width.saturating_sub(field_w) / 2;
        Paragraph::new(format!("{}_", self.token))
            .block(palette.panel(" Link token ", true))
            .style(palette.surface())
            .render(
                Rect {
                    x: field_x,
                    y,
                    width: field_w,
                    height: 3,
                },
                buf,
            );
        y += 4;

        if let Some(ref msg) = self.status {
            let status_style = if self.is_error {
                palette.state(true)
            } else {
                palette.muted()
            };
            let sx = area.x + area.width.saturating_sub(msg.len() as u16) / 2;
            Paragraph::new(msg.as_str()).style(status_style).render(
                Rect {
                    x: sx,
                    y,
                    width: (msg.len() as u16).min(area.width),
                    height: 1,
                },
                buf,
            );
            y += 2;
        }

        let hx = area.x + area.width.saturating_sub(HINT.len() as u16) / 2;
        Paragraph::new(HINT).style(palette.muted()).render(
            Rect {
                x: hx,
                y,
                width: (HINT.len() as u16).min(area.width),
                height: 1,
            },
            buf,
        );
    }

    fn render_show(&self, area: Rect, buf: &mut Buffer) {
        let palette = self.theme.palette();
        if let Some(ref msg) = self.status {
            let style = if self.is_error {
                palette.state(true)
            } else {
                palette.muted()
            };
            let w = (msg.chars().count() as u16).min(area.width);
            Paragraph::new(msg.as_str()).style(style).render(
                Rect {
                    x: area.x + area.width.saturating_sub(w) / 2,
                    y: area.y + area.height.saturating_sub(1),
                    width: w,
                    height: 1,
                },
                buf,
            );
        }
        let area = Rect {
            height: area.height.saturating_sub(2),
            ..area
        };
        match &self.own_token {
            None => {
                // Token not yet generated — show loading hint
                let msg = "Making a link code…";
                let x = area.x + area.width.saturating_sub(msg.len() as u16) / 2;
                let y = area.y + area.height / 2;
                Paragraph::new(msg).style(palette.muted()).render(
                    Rect {
                        x,
                        y,
                        width: msg.len() as u16,
                        height: 1,
                    },
                    buf,
                );
            }
            Some(code) => {
                QrWidget::new(code)
                    .caption("Link this device to your account")
                    .theme(self.theme)
                    .render(area, buf);
            }
        }
    }
}
